function formatBrlFromCentavos(centavos) {
    if (centavos === null || centavos === undefined || centavos <= 0) return "Sob Consulta";
    const reais = Math.round(centavos / 100);
    return `R$ ${reais.toLocaleString("pt-BR")}`;
}

function mapearCategoriaSga(cat = "") {
    const c = cat.toLowerCase();
    if (c.includes("headset")) return { id: "vr-headset", label: "VR & Headsets" };
    if (c.includes("esteira") || c.includes("simulador")) return { id: "simuladores", label: "Simuladores & Esteiras VR" };
    if (c.includes("haptic") || c.includes("háptic") || c.includes("acess") || c.includes("rastrea")) {
        return { id: "acessorios-vr", label: "Acessórios & Haptics VR" };
    }
    if (c.includes("totem")) return { id: "totem", label: "Totens & Quiosques" };
    if (c.includes("mesa")) return { id: "touch-table", label: "Mesas Touch" };
    if (c.includes("piso") || c.includes("proje")) return { id: "projecao", label: "Projeção & Pisos" };
    if (c.includes("sensor") || c.includes("lidar") || c.includes("kinect")) return { id: "kinect-ar", label: "Sensores 3D & AR" };
    return { id: "acessorios-vr", label: cat || "Hardware & VR" };
}

/**
 * Mescla o catálogo vindo ao vivo do SGA CTRLB (`produtosSga`) com os dados ricos
 * da landing page, aplicando o preço dinâmico (valor extraído da lojabrmetaverso + % lucro)
 * e ESCONDENDO automaticamente qualquer item que esteja:
 *  - inativo (`ativo === false` ou `vender_online === false`)
 *  - com estoque zerado (`estoque_atual <= 0` quando `controla_estoque !== false`)
 *  - indisponível na loja fonte (`indisponivel_na_fonte === true` ou `disponivel === false` ou `em_estoque === false`)
 */
export function mesclarCatalogoSga(produtosSga) {
    if (!Array.isArray(produtosSga) || produtosSga.length === 0) {
        return produtosGamificacao.filter((p) => p.inStock && (p.stockCount ?? 1) > 0);
    }

    const porSku = new Map();
    const porNome = new Map();
    for (const item of produtosSga) {
        if (item.sku) porSku.set(String(item.sku).trim().toUpperCase(), item);
        if (item.nome) porNome.set(String(item.nome).trim().toLowerCase(), item);
    }

    const usadosSgaIds = new Set();
    const resultado = [];

    for (const base of produtosGamificacao) {
        const skuKey = base.sku ? String(base.sku).trim().toUpperCase() : "";
        const sgaItem =
            (skuKey && porSku.get(skuKey)) ||
            porNome.get(base.name.trim().toLowerCase()) ||
            null;

        if (sgaItem) {
            usadosSgaIds.add(sgaItem.id);

            const ativo = sgaItem.ativo !== false && sgaItem.vender_online !== false;
            const controla = sgaItem.controla_estoque !== false;
            const saldo = typeof sgaItem.estoque_atual === "number" ? sgaItem.estoque_atual : base.stockCount;
            const disponivelFlag =
                sgaItem.disponivel !== undefined
                    ? Boolean(sgaItem.disponivel)
                    : sgaItem.em_estoque !== undefined
                      ? Boolean(sgaItem.em_estoque)
                      : (!controla || saldo > 0) && !sgaItem.indisponivel_na_fonte;

            // Esconde se inativo, estoque == 0 ou sumiu da loja fonte (lojabrmetaverso)
            if (!ativo || !disponivelFlag || (controla && saldo <= 0) || sgaItem.indisponivel_na_fonte) {
                continue;
            }

            const precoCentavos =
                sgaItem.preco_efetivo_centavos ??
                sgaItem.preco_promocional_centavos ??
                sgaItem.preco_centavos ??
                null;
            const precoReais = precoCentavos !== null ? Math.round(precoCentavos / 100) : base.priceSaleNumeric;
            const locacaoCentavos = sgaItem.preco_locacao_centavos ?? null;
            const locacaoReais =
                locacaoCentavos !== null && locacaoCentavos > 0
                    ? Math.round(locacaoCentavos / 100)
                    : base.priceRentNumeric;

            resultado.push({
                ...base,
                sgaId: sgaItem.id,
                sku: sgaItem.sku || base.sku,
                name: sgaItem.nome || base.name,
                shortDesc: sgaItem.descricao || base.shortDesc,
                image: sgaItem.imagem_url || base.image,
                inStock: true,
                stockCount: saldo > 0 ? saldo : 1,
                priceSale: precoCentavos !== null ? formatBrlFromCentavos(precoCentavos) : base.priceSale,
                priceSaleNumeric: precoReais,
                priceRent:
                    locacaoCentavos !== null && locacaoCentavos > 0
                        ? `${formatBrlFromCentavos(locacaoCentavos)} / diária`
                        : base.priceRent,
                priceRentNumeric: locacaoReais,
                parcelamentoExtraido: sgaItem.parcelamento_extraido || null,
                precoCartaoCentavos: sgaItem.preco_cartao_extraido_centavos || null,
                margemLucroPct: sgaItem.margem_lucro_pct ?? null,
                fontePrecoLoja: sgaItem.fonte_preco_loja ?? null,
            });
        } else {
            // Se o catálogo do SGA veio populado e o item não está mais ativo/presente lá,
            // só mantemos itens estáticos que não tinham vínculo de SKU com o SGA.
            if (!base.sku && base.inStock && (base.stockCount ?? 1) > 0) {
                resultado.push(base);
            }
        }
    }

    // Adiciona produtos novos que foram cadastrados diretamente no SGA CTRLB
    for (const sgaItem of produtosSga) {
        if (usadosSgaIds.has(sgaItem.id)) continue;
        if (String(sgaItem.sku || "").trim().toUpperCase().startsWith("POS-")) continue;
        const ativo = sgaItem.ativo !== false && sgaItem.vender_online !== false;
        const controla = sgaItem.controla_estoque !== false;
        const saldo = typeof sgaItem.estoque_atual === "number" ? sgaItem.estoque_atual : 1;
        const disponivelFlag =
            sgaItem.disponivel !== undefined
                ? Boolean(sgaItem.disponivel)
                : sgaItem.em_estoque !== undefined
                  ? Boolean(sgaItem.em_estoque)
                  : (!controla || saldo > 0) && !sgaItem.indisponivel_na_fonte;

        if (!ativo || !disponivelFlag || (controla && saldo <= 0) || sgaItem.indisponivel_na_fonte) {
            continue;
        }

        const cat = mapearCategoriaSga(sgaItem.categoria || "");
        const precoCentavos =
            sgaItem.preco_efetivo_centavos ?? sgaItem.preco_promocional_centavos ?? sgaItem.preco_centavos ?? null;
        const precoReais = precoCentavos !== null ? Math.round(precoCentavos / 100) : 0;
        const locacaoCentavos = sgaItem.preco_locacao_centavos ?? null;
        const locacaoReais = locacaoCentavos ? Math.round(locacaoCentavos / 100) : Math.max(120, Math.round(precoReais * 0.12));

        resultado.push({
            id: sgaItem.sku ? String(sgaItem.sku).toLowerCase() : `sga-${sgaItem.id}`,
            sgaId: sgaItem.id,
            sku: sgaItem.sku || null,
            name: sgaItem.nome,
            shortTitle: sgaItem.nome.slice(0, 28),
            tagline: sgaItem.descricao || "Produto oficial disponível na loja Unrender Games.",
            quickPitch: sgaItem.descricao || "Disponível para pronta entrega na Unrender Games.",
            tags: Array.isArray(sgaItem.selos) && sgaItem.selos.length > 0 ? sgaItem.selos : ["Pronta Entrega", cat.label],
            category: cat.id,
            categoryLabel: cat.label,
            badge: sgaItem.destaque ? "Destaque • Pronta Entrega" : "Pronta Entrega",
            badgeColor: "bg-cyan-500/20 text-cyan-300 border-cyan-500/30",
            image: sgaItem.imagem_url || "/images/CentelhaMT.jpg",
            inStock: true,
            stockCount: saldo,
            leadTime: "Pronta Entrega (Envio em 24h)",
            priceSale: formatBrlFromCentavos(precoCentavos),
            priceSaleNumeric: precoReais,
            priceRent: `${formatBrlFromCentavos(locacaoRentOrFallback(locacaoCentavos, precoCentavos))} / diária`,
            priceRentNumeric: locacaoReais,
            rating: 5.0,
            reviewsCount: 12,
            shortDesc: sgaItem.descricao || sgaItem.nome,
            longDesc: sgaItem.descricao || sgaItem.nome,
            highlights: [
                "Produto oficial com garantia e suporte técnico Unrender Games",
                "Pronta entrega com envio rápido para todo o Brasil",
                sgaItem.parcelamento_extraido || "Condições especiais no PIX ou parcelado no cartão"
            ],
            techSpecs: {
                "Categoria": sgaItem.categoria || cat.label,
                "Código / SKU": sgaItem.sku || "UNR-VR",
                "Disponibilidade": `${saldo} ${sgaItem.unidade_medida || "un"} em estoque`
            },
            softwareModes: ["Compatível com ecossistema VR / Interativo Unrender Games"],
            idealFor: ["Eventos corporativos, arenas VR e uso entusiasta"],
            parcelamentoExtraido: sgaItem.parcelamento_extraido || null,
            whatsappMessage: `Olá! Gostaria de comprar / orçar o produto "${sgaItem.nome}" na loja da Unrender Games.`
        });
    }

    return resultado;
}

function locacaoRentOrFallback(locacaoCentavos, precoCentavos) {
    if (locacaoCentavos && locacaoCentavos > 0) return locacaoCentavos;
    if (precoCentavos && precoCentavos > 0) return Math.max(10000, Math.round(precoCentavos * 0.12));
    return null;
}
